/** Собирает v1.2.1-dev для запуска двойным кликом по index.html. */
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const assets = resolve(root, 'v1.2.1-dev', 'assets');
const moduleNames = ['character-state.js', 'character-xml.js', 'dom.js', 'drag-reorder.js', 'libraries/traits.js', 'app.js'];
const sources = await Promise.all(moduleNames.map(name => readFile(resolve(assets, name), 'utf8')));
const bundle = sources.map((source, index) => {
  const classic = source
    .replace(/^import[^;]+;\r?\n/gm, '')
    .replace(/\bexport const /g, 'const ')
    .replace(/\bexport function /g, 'function ')
    .replace(/^export \{[^}]+\};\r?\n?/gm, '');
  return `/* ${moduleNames[index]} */\n${classic}`;
}).join('\n\n');

await writeFile(resolve(assets, 'app.bundle.js'), `/* Generated by tools/bundle-v121.mjs. Do not edit directly. */\n\n${bundle}`, 'utf8');
console.log('Создан v1.2.1-dev/assets/app.bundle.js.');
