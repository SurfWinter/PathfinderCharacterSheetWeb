const SKILL_RENAMES = { 'Аркана':'Мистицизм', 'Введение в заблуждение':'Обман' };
function migrateSkills(skills){
  if(!Array.isArray(skills)) return null;
  return skills.map(s=>{
    if(!s.multi && SKILL_RENAMES[s.name]) return Object.assign({}, s, {name: SKILL_RENAMES[s.name]});
    return s;
  });
}


function migrateAbilities(raw){
  const result = {};
  ['str','dex','con','int','wis','cha'].forEach(k=>{
    const v = raw ? raw[k] : undefined;
    if(v && typeof v === 'object' && ('mod' in v)){
      result[k] = {mod:Number(v.mod)||0, partial: !!v.partial};
    } else if(typeof v === 'number'){
      result[k] = {mod: Math.floor((v-10)/2), partial:false};
    } else {
      result[k] = {mod:0, partial:false};
    }
  });
  return result;
}

function normalizeTraits(raw){
  const values = Array.isArray(raw) ? raw : (!raw ? [] : String(raw).split(','));
  return values.map(trait=>{
    if(trait && typeof trait === 'object' && trait.type === 'library' && typeof trait.id === 'string'){
      return {type:'library', id:trait.id};
    }
    const name = typeof trait === 'string' ? trait.trim() : (trait && trait.name ? String(trait.name).trim() : '');
    if(!name) return null;
    const library = matchLibraryTrait(name);
    if(library) return {type:'library', id:library.id};
    return {type:'custom', name};
  }).filter(Boolean);
}
function splitTraitsString(s){
  return normalizeTraits(s);
}
function actionNameKey(name){
  return String(name || '').trim().toLocaleLowerCase('ru');
}
function basicActionKey(action){
  if(action && action.id) return String(action.id);
  return actionNameKey(action && action.name);
}
function instantiateBasicAction(a){
  return {
    id: uid(),
    basicId: basicActionKey(a),
    name: a.name,
    type: a.type,
    traits: splitTraitsString(a.traits),
    desc: a.desc,
    fromFeat: false,
    favorite: false,
  };
}
function migrateActions(actions){
  if(!Array.isArray(actions)) return null;
  const byName = new Map(BASIC_ACTIONS.map(b => [actionNameKey(b.name), b]));
  const migrated = actions.map(a=>{
    const next = Object.assign({}, a, {traits: normalizeTraits(a.traits), favorite: !!a.favorite});
    if(!next.basicId){
      const match = byName.get(actionNameKey(a.name));
      if(match) next.basicId = basicActionKey(match);
    }
    return next;
  });
  const presentIds = new Set(migrated.map(a=>a.basicId).filter(Boolean));
  const presentNames = new Set(migrated.map(a=>actionNameKey(a.name)));
  BASIC_ACTIONS.forEach(b=>{
    const id = basicActionKey(b);
    const name = actionNameKey(b.name);
    if(presentIds.has(id) || presentNames.has(name)) return;
    migrated.push(instantiateBasicAction(b));
    presentIds.add(id);
    presentNames.add(name);
  });
  return migrated;
}
